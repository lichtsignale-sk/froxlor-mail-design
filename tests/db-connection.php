<?php

/**
 * Tests that the database settings are read from lib/userdata.inc.php exactly
 * as Froxlor writes and reads them (socket, host/port, TLS block), using fake
 * userdata files; no database needed:
 *
 *   php tests/db-connection.php
 */

if (PHP_SAPI !== 'cli') {
	http_response_code(404);
	exit(1);
}

error_reporting(E_ALL);
set_error_handler(static function (int $no, string $msg, string $file, int $line): bool {
	if (!(error_reporting() & $no)) {
		return false;
	}
	throw new ErrorException($msg, 0, $no, $file, $line);
});

require __DIR__ . '/../lib/Froxlor/Ext/MailDesign/DbConnection.php';

use Froxlor\Ext\MailDesign\DbConnection;

if (!extension_loaded('pdo_mysql')) {
	echo "  SKIP (pdo_mysql not available)\n";
	exit(0);
}

$failures = 0;
$check = static function (bool $ok, string $what) use (&$failures): void {
	echo ($ok ? '  ok   ' : '  FAIL ') . $what . "\n";
	$failures += $ok ? 0 : 1;
};

$dir = sys_get_temp_dir() . '/md-db-' . bin2hex(random_bytes(4));
mkdir($dir . '/lib', 0700, true);
$userdata = static function (array $sql) use ($dir): string {
	// Same layout as Froxlor's installer (lib/Froxlor/Install/Install/Core.php) writes.
	file_put_contents($dir . '/lib/userdata.inc.php', "<?php\n\$sql = " . var_export($sql, true) . ";\n\$sql_root = [];\n");
	return $dir;
};
$ssl = DbConnection::mysqlAttribute('SSL_CA');
$verify = DbConnection::mysqlAttribute('SSL_VERIFY_SERVER_CERT');

// Plain host, default port
$c = DbConnection::config($userdata(['host' => 'db.example.org', 'user' => 'froxlor', 'password' => 'pw', 'db' => 'froxlor']));
$check($c['dsn'] === 'mysql:charset=utf8;dbname=froxlor;host=db.example.org;port=3306', 'host with default port 3306');
$check($c['user'] === 'froxlor' && $c['password'] === 'pw' && !isset($c['options'][$ssl]), 'credentials, no TLS');

// Explicit port and TLS block
$c = DbConnection::config($userdata([
	'host' => '10.0.0.5', 'port' => '3307', 'user' => 'froxlor', 'password' => 'pw', 'db' => 'froxlor',
	'ssl' => ['caFile' => '/etc/mysql/ca.pem', 'verifyServerCertificate' => true],
]));
$check($c['dsn'] === 'mysql:charset=utf8;dbname=froxlor;host=10.0.0.5;port=3307', 'port from $sql[\'port\']');
$check(($c['options'][$ssl] ?? null) === '/etc/mysql/ca.pem' && ($c['options'][$verify] ?? null) === true, 'TLS CA file and verification from $sql[\'ssl\']');

$c = DbConnection::config($userdata([
	'host' => 'db', 'user' => 'u', 'password' => 'p', 'db' => 'd',
	'ssl' => ['caFile' => '/ca.pem', 'verifyServerCertificate' => false],
]));
$check(($c['options'][$verify] ?? null) === false, 'verification can be off');

// Socket wins over host, like Froxlor (no TLS options on a socket)
$c = DbConnection::config($userdata([
	'host' => 'localhost', 'socket' => '/run/mysqld/mysqld.sock', 'user' => 'u', 'password' => 'p', 'db' => 'd',
	'ssl' => ['caFile' => '/ca.pem', 'verifyServerCertificate' => true],
]));
$check($c['dsn'] === 'mysql:charset=utf8;dbname=d;unix_socket=/run/mysqld/mysqld.sock' && !isset($c['options'][$ssl]), 'unix socket used, no host/port');

// Old-style keys are not interpreted (Froxlor 2.x does not write them)
$c = DbConnection::config($userdata(['host' => 'db:3310', 'user' => 'u', 'password' => 'p', 'db' => 'd', 'ssl_ca_file' => '/x.pem']));
$check(!isset($c['options'][$ssl]) && str_contains($c['dsn'], 'host=db:3310;port=3306'), 'no host:port parsing, no ssl_ca_file key (as Froxlor)');

// Broken files
file_put_contents($dir . '/lib/userdata.inc.php', "<?php\n\$nothing = 1;\n");
try {
	DbConnection::config($dir);
	$check(false, 'missing $sql refused');
} catch (RuntimeException $e) {
	$check(true, 'missing $sql refused');
}
try {
	DbConnection::config($dir . '/missing');
	$check(false, 'missing userdata.inc.php refused');
} catch (RuntimeException $e) {
	$check(true, 'missing userdata.inc.php refused');
}

// userdata.inc.php is parsed, never executed
$marker = $dir . '/executed';
file_put_contents($dir . '/lib/userdata.inc.php', "<?php\nfile_put_contents(" . var_export($marker, true) . ", 'x');\n\$sql = ['host' => 'h', 'user' => 'u', 'password' => 'p', 'db' => 'd'];\n");
try {
	DbConnection::config($dir);
	$check(false, 'code in userdata.inc.php refused');
} catch (RuntimeException $e) {
	$check(!is_file($marker) && !str_contains($e->getMessage(), 'file_put_contents'), 'code in userdata.inc.php refused, not executed, not echoed');
}
file_put_contents($dir . '/lib/userdata.inc.php', "<?php\n\$sql = ['host' => \"h\$x\", 'user' => 'u', 'db' => 'd'];\n");
try {
	DbConnection::config($dir);
	$check(false, 'interpolated string refused');
} catch (RuntimeException $e) {
	$check(true, 'interpolated string refused');
}

// Format written by Froxlor's installer: short arrays, nowdoc passwords, element assignments
file_put_contents($dir . '/lib/userdata.inc.php', <<<'PHP'
<?php
// autogenerated froxlor file
$sql = [
	'debug' => false,
	'host' => 'db.example.org',
	'user' => 'froxlor',
	'password' => <<<'EOT'
pa'ss"w$rd\n
EOT,
	'db' => 'froxlor',
];
$sql['port'] = 3308;
$sql_root = array('0' => array('caption' => 'Default', 'user' => 'root', 'password' => 'x'));
PHP);
$c = DbConnection::config($dir);
$check($c['password'] === 'pa\'ss"w$rd\n' && str_ends_with($c['dsn'], 'host=db.example.org;port=3308') && $c['local'] === false, 'nowdoc password, element assignment, remote host');
$check(DbConnection::config($userdata(['socket' => '/run/mysqld/mysqld.sock', 'user' => 'u', 'db' => 'd']))['local'] === true, 'socket counts as local');

// A symbolic link in place of userdata.inc.php is refused
rename($dir . '/lib/userdata.inc.php', $dir . '/real.php');
symlink($dir . '/real.php', $dir . '/lib/userdata.inc.php');
try {
	DbConnection::config($dir);
	$check(false, 'symbolic link refused');
} catch (RuntimeException $e) {
	$check(true, 'symbolic link refused');
}
unlink($dir . '/real.php');
@unlink($marker);

unlink($dir . '/lib/userdata.inc.php');
rmdir($dir . '/lib');
rmdir($dir);

echo $failures === 0 ? "All tests passed\n" : "$failures test(s) failed\n";
exit($failures > 0 ? 1 : 0);
